def npc553_rates(rule, prior=None):
    """Spending as a fraction of the current value and of the NPC 553(d) average, year by year, for one rule run on its
    OWN asset path: each rule's quarter-end values come from its own spending. `prior` holds the 20 quarter-end
    values before the simulation (assumed flat at 2,000m); passing another rule's history reproduces the old error.
    """
    quarters = list(prior) if prior is not None else [MV0] * 20
    mv, sp, cur, avg = MV0, SPEND_RATE * MV0, [], []
    for rr in returns:
        sp = SPEND_RATE * mv if rule == "pure" else 0.7 * sp * (1 + INFL) + 0.3 * SPEND_RATE * mv
        avg5 = (
            sum(quarters[-20:]) / 20
        )  # NPC 553(d): quarterly values averaged over the five preceding years
        cur.append(sp / mv)
        avg.append(sp / avg5)
        start = mv - sp
        quarters += [start * (1 + rr) ** (q / 4) for q in range(1, 5)]
        mv = start * (1 + rr)
    return cur, avg, quarters


