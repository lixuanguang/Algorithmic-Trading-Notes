# Statutory minimum for the plan year beginning 1 January 2026 (valuation date, 430(g)(2)(A)). Stated assumptions:
# one 5% effective rate stands in for the segment rates; installments fall on the valuation date of each plan year;
# bases set in 2022-2025 (USD bn, as each year's valuation determined them) are the only open bases, since 430(c)(8)
# zeroed earlier ones and every year since had a shortfall (otherwise 430(c)(6) would have zeroed them); no waiver
# bases, prefunding or carryover balances; target normal cost 0.110bn (benefits accruing in 2026 plus expenses).
R_FUND, N_AMORT, TNC, YEAR = 0.05, 15, 0.110, 2026
PRIOR_BASES = {2022: 0.20, 2023: 0.08, 2024: 0.03, 2025: 0.05}


def adue(n, r=R_FUND):
    """Annuity-due factor: n level installments, the first on the valuation date."""
    return annuity(r, n) * (1 + r) if n > 0 else 0.0


def min_required(assets, ft, tnc, prior, year=YEAR):
    """430(a), (c): returns (minimum required contribution, new base, PV of old installments, old installments)."""
    if (
        assets >= ft
    ):  # 430(a)(2), (c)(5)-(6): no new base, earlier bases zeroed, TNC less the excess
        return max(0.0, tnc - (assets - ft)), 0.0, 0.0, 0.0
    inst = {y: b / adue(N_AMORT) for y, b in prior.items()}
    left = {y: N_AMORT - (year - y) for y in prior}  # installments still due, this year's included
    pv_old = sum(inst[y] * adue(left[y]) for y in prior)
    new_base = (ft - assets) - pv_old  # 430(c)(3): shortfall less PV of existing installments
    charge = max(
        0.0, sum(inst.values()) + new_base / adue(N_AMORT)
    )  # 430(c)(1): not less than zero
    return tnc + charge, new_base, pv_old, sum(inst.values())


