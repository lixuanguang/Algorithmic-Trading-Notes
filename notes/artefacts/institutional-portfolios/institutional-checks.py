"""Institutional portfolios: pension risk, IPS and portfolio evaluation, a sovereign fund risk case, endowment liquidity
and ESG constraints (2026-10-20).

Worked numbers of the entries in compendium/portfolio-construction-risk/institutional-portfolios.tex. Every
institution is hypothetical (Harlow Industrial's DB plan, the Elmsworth University endowment, the Calder Foundation,
Bank Ardent and the Vardø Fund, a commodity sovereign fund), except the published benchmark parameters of Norway's
Government Pension Fund Global quoted in the entries (NBIM web pages, 2026).

Pension measures (part 1). The accounting PBO (9.0bn) projects final salaries and discounts at an ASC 715 corporate
rate; the statutory funding target of a US single-employer plan (IRC 430(d)(1)) is the present value of benefits
accrued at the start of the plan year, at stabilised segment rates (430(h)(2)); an economic liability discounts the
promised benefits at near risk-free rates. For plan years beginning after 31 December 2021 (earlier by election),
430(c)(8), added by ARPA 2021 sec. 9705 (IRS Notice 2021-48, IRB 2021-33), reduced earlier shortfall bases to zero and
amortises each new shortfall base over 15 plan years instead of 7. The minimum required contribution is target normal
cost plus the installments on all open bases (430(a)); it is not an annuity on the accounting deficit. Each year's new
base is the funding shortfall LESS the present value of the installments still due on earlier bases (430(c)(3); Notice
2021-48 sec. III.B.1), so the open bases together always amortise exactly the current shortfall. The funding target of
8.4bn, the 2022-2025 bases, the 110m target normal cost, a single 5% effective rate in place of the segment rates and
the 0.75-point Treasury spread are stylised assumptions, not Harlow's actuarial valuation.

Endowment law (part 2). Elmsworth is a New York not-for-profit corporation; its endowment is donor-restricted under gift
instruments executed after the effective date of New York's Prudent Management of Institutional Funds Act, none of
which sets a spending rate. NPC 553(d) presumes imprudence for an appropriation above 7% of fair market value averaged
over quarterly values for at least the five preceding years; spending at or below 7% creates no presumption of
prudence, which turns on the factors in 553(a). The five years of quarterly history before the simulation are a stated
assumption (flat at 2,000m).

Corrections (2026-10-20, final audit): the deficit annuity over seven years was presented as the current legal
requirement; the UPMIFA check compared spending with the current value instead of the statutory average and read 7% as
a safe harbour; remaining liquidity deducted gross needs although coverage netted distributions.

Corrections (2026-10-21, PR #33 correction pass): the pure 5% rule's NPC 553(d) ratios divided its spending by
quarterly values generated by the smoothed rule (peak 5.25%); each rule now carries its own quarterly history (pure
peak 5.242401%, 5.24%), and a check rebuilds the pure history and shows the cross-policy construction differs.
The Harlow minimum treated the whole 0.40bn shortfall as a new base and then added installments on earlier bases,
amortising the 303.2m of open bases twice; the new base is now 96.8m under 430(c)(3), the contribution is computed in
full (151.91m at the valuation date, of which 41.91m repairs the shortfall) and its timing stated.

Independent routes: surplus volatility from the covariance matrix against a Monte Carlo of asset and liability
returns; hedge ratios from dollar durations; deficit amortisation against an annuity schedule; the 430(c)(3)
bases by the identity that all open installments have a present value equal to the shortfall, and boundary cases; spending rules
simulated year by year against closed forms; the equity duration gap against a full repricing of assets and
liabilities; the GPFG rebalancing trigger by rule; stress-test liquidity coverage summed source by source; the
denominator effect by recomputing weights; exclusion tracking error against a simulated active return.

Count convention: one check is one executed ok() call (a call inside a loop counts once per iteration).

Run: uv run python institutional-checks.py   (numpy). Exits 1 on failure.
"""

